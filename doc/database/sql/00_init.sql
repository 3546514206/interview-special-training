INSERT INTO users (name, phone, age, gender, status, create_time)
SELECT
    CONCAT('用户', n)               AS name,
    CONCAT('139', LPAD(n, 8, '0'))  AS phone,
    20 + (n MOD 30)                AS age,
    IF(n MOD 2 = 0, 1, 2)          AS gender,
    IF(n MOD 50 = 0, 0, 1)         AS status,
    DATE_ADD('2026-01-01 10:00:00', INTERVAL n HOUR) AS create_time
FROM (
    SELECT a.N + b.N * 10 + c.N * 100 AS n
    FROM (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
          UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) a
    CROSS JOIN (SELECT 0 AS N UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4
                UNION SELECT 5 UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9) b
    CROSS JOIN (SELECT 0 AS N UNION SELECT 1) c
) seq
WHERE n BETWEEN 61 AND 200;

